<#
.SYNOPSIS
    将 claude-risk-check（Claude 账号风控自检工具：网页自检页 + Python CLI）
    一键安装到本机，并可选注册全局命令 claude-risk-check。

.DESCRIPTION
    1. 定位可用的 Python 解释器（.venv → python.exe/py.exe → uv 托管）
    2. 复制运行所需全部文件到用户空间 %USERPROFILE%\.claude-risk-check\
       （index.html / questions.js / questions.json / claude_risk_check.py / probe.py）
    3. 在 %USERPROFILE%\.local\bin\ 生成 launcher：claude-risk-check.cmd
    4. 校验 CLI 与 launcher 可运行（--help）
    5. 打印使用说明（HTML 页面路径 + 命令用法）
    全程幂等，可重复执行；不会改动任何系统环境变量。

.PARAMETER InstallDir
    安装目录，默认 %USERPROFILE%\.claude-risk-check

.PARAMETER BinDir
    launcher 输出目录，默认 %USERPROFILE%\.local\bin（需已在 PATH 中；不在则给出提示）

.PARAMETER Python
    指定 Python 解释器完整路径；不指定则自动探测。

.PARAMETER NoLauncher
    只复制文件，不生成全局命令 claude-risk-check。

.PARAMETER Open
    安装完成后用默认浏览器打开 index.html 自检页。

.EXAMPLE
    .\scripts\install.ps1
    .\scripts\install.ps1 -Open
    .\scripts\install.ps1 -Python "D:\Python312\python.exe" -InstallDir "D:\tools\claude-risk-check"
#>
[CmdletBinding()]
param(
    [string]$InstallDir = (Join-Path $env:USERPROFILE ".claude-risk-check"),
    [string]$BinDir = (Join-Path $env:USERPROFILE ".local\bin"),
    [string]$Python = "",
    [switch]$NoLauncher,
    [switch]$Open
)

$ErrorActionPreference = "Stop"
$ProjectRoot = Split-Path -Parent $PSScriptRoot
$Utf8Bom = New-Object System.Text.UTF8Encoding($true)
# .cmd 由 cmd.exe 按系统 ANSI 代码页读取，故 launcher 用 ANSI 写，避免中文路径乱码
$Ansi = [System.Text.Encoding]::GetEncoding([System.Globalization.CultureInfo]::CurrentCulture.TextInfo.ANSICodePage)

function Assert-Path($path, $label) {
    if (-not (Test-Path $path)) { throw "$label 不存在：$path" }
}
function Write-Utf8Bom($path, $text) { [System.IO.File]::WriteAllText($path, $text, $Utf8Bom) }
function Write-Ansi($path, $text) { [System.IO.File]::WriteAllText($path, $text, $Ansi) }
# 把绝对路径转成可在 .cmd 中安全使用的表达式：优先用 %APPDATA%/%USERPROFILE% 等
# 运行时展开的环境变量，避免把中文等非 ASCII 字节写进 .cmd（其解析受控制台代码页影响）
function To-CmdPath([string]$path) {
    $roots = @(
        @{ n = '%APPDATA%';      v = $env:APPDATA },
        @{ n = '%LOCALAPPDATA%'; v = $env:LOCALAPPDATA },
        @{ n = '%USERPROFILE%';  v = $env:USERPROFILE },
        @{ n = '%TEMP%';         v = $env:TEMP }
    )
    foreach ($r in $roots) {
        if ($r.v -and $path.StartsWith($r.v, [System.StringComparison]::OrdinalIgnoreCase)) {
            return $r.n + $path.Substring($r.v.Length)
        }
    }
    if ($path -match '^[\x00-\x7F]+$') { return $path }
    throw "路径含非 ASCII 字符且不在 APPDATA/USERPROFILE 等目录下，无法生成安全的 launcher：$path"
}

# --- 0. 源文件核验 ---
$srcFiles = @(
    "index.html",
    "questions.js",
    "questions.json",
    "claude_risk_check.py",
    "probe.py"
)
$srcPaths = @{}
foreach ($name in $srcFiles) {
    $p = Join-Path $ProjectRoot $name
    Assert-Path $p $name
    $srcPaths[$name] = $p
}
$srcHtml = $srcPaths["index.html"]
$srcPy = $srcPaths["claude_risk_check.py"]

# --- 1. 定位 Python 解释器 ---
function Resolve-Python([string]$Explicit) {
    if ($Explicit) { Assert-Path $Explicit "指定的 Python"; return $Explicit }
    $cands = @()
    $cands += (Join-Path $ProjectRoot ".venv\Scripts\python.exe")
    foreach ($n in @("python.exe", "python3.exe", "py.exe")) {
        $c = Get-Command $n -ErrorAction SilentlyContinue
        if ($c) { $cands += $c.Source }
    }
    foreach ($p in $cands) { if ($p -and (Test-Path $p)) { return $p } }
    # 兜底：uv 托管的 python
    $uvPath = Join-Path $env:USERPROFILE ".local\bin\uv.exe"
    if (Test-Path $uvPath) {
        try {
            $found = & $uvPath python find 2>$null
            if ($LASTEXITCODE -eq 0 -and $found) {
                $found = "$found".Trim()
                if (Test-Path $found) { return $found }
            }
        } catch { }
    }
    throw "未找到 Python 解释器。请先安装 Python 3.8+，或用 -Python 指定完整路径。"
}

$pythonPath = Resolve-Python $Python
Write-Host "[1/5] Python 解释器：$pythonPath" -ForegroundColor Cyan

# --- 2. 复制工具到用户空间 ---
New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
foreach ($name in $srcFiles) {
    Copy-Item $srcPaths[$name] (Join-Path $InstallDir $name) -Force
}
$installedPy = Join-Path $InstallDir "claude_risk_check.py"
$installedHtml = Join-Path $InstallDir "index.html"
Write-Host "[2/5] 已复制 $($srcFiles.Count) 个文件到：$InstallDir" -ForegroundColor Cyan

# --- 3. 生成全局命令 claude-risk-check.cmd ---
$launcherPath = $null
if ($NoLauncher) {
    Write-Host "[3/5] 已按 -NoLauncher 跳过全局命令生成" -ForegroundColor Yellow
}
else {
    New-Item -ItemType Directory -Force -Path $BinDir | Out-Null
    $launcherPath = Join-Path $BinDir "claude-risk-check.cmd"
    # 两个坑：cmd.exe 要求 CRLF 换行（LF 会报 'm' is not recognized）；.cmd 内的非 ASCII 字节受控制台代码页影响。
    # 故用 CRLF 拼接，并用 %APPDATA%/%USERPROFILE% 表达式替换绝对路径，使 launcher 内容为纯 ASCII。
    $pyExpr = To-CmdPath $pythonPath
    $scriptExpr = To-CmdPath $installedPy
    $cmdText = @(
        '@echo off',
        'rem claude-risk-check launcher (generated by scripts/install.ps1)',
        ('"{0}" "{1}" %*' -f $pyExpr, $scriptExpr)
    ) -join "`r`n"
    $cmdText += "`r`n"
    Write-Ansi $launcherPath $cmdText
    $onPath = ($env:Path -split ';') | Where-Object { $_.TrimEnd('\') -ieq $BinDir.TrimEnd('\') }
    if ($onPath) {
        Write-Host "[3/5] 已生成全局命令：$launcherPath（$BinDir 已在 PATH）" -ForegroundColor Cyan
    }
    else {
        Write-Host "[3/5] 已生成 launcher：$launcherPath" -ForegroundColor Cyan
        Write-Host "     提示：$BinDir 不在当前 PATH 中，新开终端后可能无法直接调用；建议把 $BinDir 加入 PATH。" -ForegroundColor Yellow
    }
}

# --- 4. 校验 CLI 与 launcher 可运行 ---
$null = & $pythonPath $installedPy --help 2>&1
if ($LASTEXITCODE -ne 0) { throw "CLI 自检失败：$pythonPath $installedPy --help 返回 $LASTEXITCODE" }
if ($launcherPath -and (Test-Path $launcherPath)) {
    $null = & $launcherPath --help 2>&1
    if ($LASTEXITCODE -ne 0) { throw "launcher 自检失败：$launcherPath --help 返回 $LASTEXITCODE" }
}
Write-Host "[4/5] CLI 与 launcher 自检通过（--help）" -ForegroundColor Cyan

# --- 5. 使用说明 ---
Write-Host "[5/5] 安装完成" -ForegroundColor Green
Write-Host ""
Write-Host "使用方式：" -ForegroundColor Green
Write-Host "  · 网页版自检页：双击打开 $installedHtml"
if ($launcherPath) { Write-Host "  · 命令行自检：claude-risk-check          （或 `"$launcherPath`"）" }
Write-Host "  · 命令行参数：claude-risk-check --json   （输出机器可读结果）" -ForegroundColor DarkGray
Write-Host ""
Write-Host "说明：本工具基于社区封号案例与 Anthropic 公开文档归纳，仅供自查参考，" -ForegroundColor DarkGray
Write-Host "      不代表对封号结果的预测，也不构成规避平台规则的保证。" -ForegroundColor DarkGray

if ($Open) {
    Start-Process $installedHtml
    Write-Host ""
    Write-Host "已在默认浏览器打开自检页。" -ForegroundColor Cyan
}
